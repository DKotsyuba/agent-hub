/** Locale tools format structured fixture values; source prose is never transformed. */
export interface LocaleTools {
  /** Current stable preference, independent of navigation state. */
  locale: Locale;
  /** BCP 47 tag for search and native Intl formatting. */
  tag: 'ru-RU' | 'en-GB';
  /** Interpolates only an authored UI key; values are plain strings or numbers, never HTML. */
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
  /** Formats a producer's explicit percentage in the0..100 domain without recomputing it. */
  percent: (value: number) => string;
  /** Formats finite demonstration counts and numeric observations. */
  n: (value: number) => string;
  /** Formats an ISO timestamp's calendar date in the demonstration's explicit Belgrade timezone. */
  date: (iso: string) => string;
  /** Formats an ISO timestamp's local clock time in that same timezone. */
  time: (iso: string) => string;
  /** Formats a complete ISO observation timestamp without inventing freshness. */
  datetime: (iso: string) => string;
  /** Formats observed milliseconds in seconds/minutes/hours/days; null remains unknown. */
  duration: (milliseconds: number | null) => string;
  /** Formats a saved nonnegative byte measurement as binary MiB; null remains unknown. */
  size: (bytes: number | null) => string;
  /** Formats an observed count with the locale's grammatical noun form. */
  count: (value: number, noun: CountNoun) => string;
}
/** Creates native locale formatters. Callers supply finite numbers and valid ISO timestamps; invalid dates throw RangeError. */
export function createLocaleTools(locale: Locale): LocaleTools {
  /** Localization is independent of the machine's language and timezone. */
  const tag = locale === 'ru' ? 'ru-RU' : 'en-GB';
  /** Both dictionaries have exactly the same statically checked keys. */
  const dictionary = locale === 'ru' ? ru : en;
  /** Numeric format used for source-independent counts and binary measurements. */
  const number = new Intl.NumberFormat(tag, { maximumFractionDigits: 1 });
  /** Saved source estimates/quotas are percentages, never inferred progress. */
  const percentage = new Intl.NumberFormat(tag, { style: 'percent', maximumFractionDigits: 1 });
  /** All structured fixture timestamps represent observations in Belgrade. */
  const options = { timeZone: 'Europe/Belgrade' };
  /** Date-only presentation for headings. */
  const calendar = new Intl.DateTimeFormat(tag, { ...options, day: 'numeric', month: 'long', year: 'numeric' });
  /** Clock presentation for history rows. */
  const clock = new Intl.DateTimeFormat(tag, { ...options, hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
  /** Complete saved-observation presentation. */
  const timestamp = new Intl.DateTimeFormat(tag, { ...options, dateStyle: 'long', timeStyle: 'short', hourCycle: 'h23' });
  /** Native unit formatting handles second/minute/hour/day abbreviations for both locales. */
  const units = (['second', 'minute', 'hour', 'day'] as const).map(unit => new Intl.NumberFormat(tag, { style: 'unit', unit, unitDisplay: 'short', maximumFractionDigits: 0 }));
  /** Native plural categories drive explicit noun forms, including Russian 1/2/5/21. */
  const plural = new Intl.PluralRules(tag);
  /** Message interpolation is plain text; absent parameters remain visibly identifiable. */
  const t: LocaleTools['t'] = (key, values = {}) => dictionary[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
  return {
    locale, tag, t, percent: value => percentage.format(value / 100), n: value => number.format(value), date: iso => calendar.format(new Date(iso)),
    time: iso => clock.format(new Date(iso)), datetime: iso => timestamp.format(new Date(iso)),
    duration: milliseconds => milliseconds === null ? t('No information') : milliseconds < 60_000 ? units[0].format(milliseconds / 1000) : milliseconds < 3_600_000 ? units[1].format(milliseconds / 60_000) : milliseconds < 86_400_000 ? units[2].format(milliseconds / 3_600_000) : units[3].format(milliseconds / 86_400_000),
    size: bytes => bytes === null ? t('No information') : number.format(bytes / 1_048_576) + ' ' + t('MiB'),
    count: (value, noun) => {
      /** Unsupported CLDR categories use other, which is explicitly defined for every noun. */
      const forms = nouns[locale][noun];
      /** Russian uses one/few/many; fractional values and English plurals use other. */
      const category = plural.select(value);
      return number.format(value) + ' ' + forms[category === 'one' || category === 'few' || category === 'many' ? category : 'other'];
    },
  };
}
